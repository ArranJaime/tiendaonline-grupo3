using Amazon.S3;
using Amazon.S3.Model;
using Npgsql;
using System.Globalization;

// Usage: dotnet run --project Worker -- --source local --file ./examples/products.csv
//    or: dotnet run --project Worker -- --source s3 --bucket BUCKET --key supplier/products.csv
// Credentials: local AWS profile or EC2 IAM role; never embed access keys.

var argsMap = new Dictionary<string, string>();
for (int i = 0; i < args.Length - 1; i += 2)
{
    if (args[i].StartsWith("--")) argsMap[args[i][2..]] = args[i + 1];
}

string value(string name, string fallback = "") => argsMap.GetValueOrDefault(name, fallback);

var db = Environment.GetEnvironmentVariable("ConnectionStrings__Postgres")
    ?? value("connection", "Host=localhost;Port=5432;Database=urponline;Username=urponline;Password=localonly");

string source = value("source", "local");
using var reader = new StreamReader(await OpenFile());
await using var conn = new NpgsqlConnection(db);
await conn.OpenAsync();

await using (var create = new NpgsqlCommand(
    "CREATE TABLE IF NOT EXISTS \"SupplierImports\" (\"Id\" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"ImportedUtc\" timestamp with time zone NOT NULL, \"Source\" varchar(250) NOT NULL, \"Accepted\" integer NOT NULL, \"Rejected\" integer NOT NULL)",
    conn))
{
    await create.ExecuteNonQueryAsync();
}

var accepted = 0;
var rejected = 0;
string? line = await reader.ReadLineAsync(); // header id,name,description,price,stock,category,emoji

while ((line = await reader.ReadLineAsync()) != null)
{
    if (string.IsNullOrWhiteSpace(line)) continue;
    var parts = line.Split(',');
    if (parts.Length < 6 
        || !int.TryParse(parts[0], out var id) 
        || !decimal.TryParse(parts[3], NumberStyles.Number, CultureInfo.InvariantCulture, out var price) 
        || !int.TryParse(parts[4], out var stock) 
        || price < 0 
        || stock < 0)
    {
        rejected++;
        continue;
    }

    // Upsert in one statement; identifiers are parameters, never SQL string interpolation.
    await using var cmd = new NpgsqlCommand(
        "INSERT INTO \"Products\" (\"Id\",\"Name\",\"Description\",\"Price\",\"Stock\",\"Category\",\"Emoji\") " +
        "VALUES (@id,@name,@desc,@price,@stock,@cat,@emoji) " +
        "ON CONFLICT (\"Id\") DO UPDATE SET " +
        "\"Name\"=excluded.\"Name\", \"Description\"=excluded.\"Description\", \"Price\"=excluded.\"Price\", " +
        "\"Stock\"=excluded.\"Stock\", \"Category\"=excluded.\"Category\", \"Emoji\"=excluded.\"Emoji\"",
        conn);

    cmd.Parameters.AddWithValue("id", id);
    cmd.Parameters.AddWithValue("name", parts[1]);
    cmd.Parameters.AddWithValue("desc", parts[2]);
    cmd.Parameters.AddWithValue("price", price);
    cmd.Parameters.AddWithValue("stock", stock);
    cmd.Parameters.AddWithValue("cat", parts[5]);
    cmd.Parameters.AddWithValue("emoji", parts.Length > 6 ? parts[6] : "📦");

    try
    {
        await cmd.ExecuteNonQueryAsync();
        accepted++;
    }
    catch (PostgresException)
    {
        rejected++;
    }
}

await using (var rec = new NpgsqlCommand(
    "INSERT INTO \"SupplierImports\" (\"ImportedUtc\",\"Source\",\"Accepted\",\"Rejected\") VALUES (now(),@src,@a,@r)",
    conn))
{
    rec.Parameters.AddWithValue("src", source + ":" + value("file", value("key")));
    rec.Parameters.AddWithValue("a", accepted);
    rec.Parameters.AddWithValue("r", rejected);
    await rec.ExecuteNonQueryAsync();
}

Console.WriteLine($"Imported={accepted}, Rejected={rejected}");

async Task<Stream> OpenFile()
{
    if (source == "local")
    {
        return File.OpenRead(value("file", "examples/products.csv"));
    }
    if (source == "s3")
    {
        var region = value("region", Environment.GetEnvironmentVariable("AWS_REGION") ?? "us-east-2");
        using var client = new AmazonS3Client(Amazon.RegionEndpoint.GetBySystemName(region));
        var response = await client.GetObjectAsync(new GetObjectRequest
        {
            BucketName = value("bucket"),
            Key = value("key")
        });
        var ms = new MemoryStream();
        await response.ResponseStream.CopyToAsync(ms);
        ms.Position = 0;
        return ms;
    }
    throw new ArgumentException("--source must be local or s3");
}
